  var D2R = Math.PI / 180;
  function vec(lat, lon) {
    var p = lat * D2R, l = lon * D2R;
    return [Math.cos(p) * Math.cos(l), Math.cos(p) * Math.sin(l), Math.sin(p)];
  }
  FA.vec = vec;
  function cross(a, b) { return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]; }
  FA.cross = cross;

  // Packar domer för shadern: tre vec4 per dom
  FA.domeUniforms = function (bp, out) {
    var C = out.C, T = out.T, S = out.S, i, n = 0;
    for (i = 0; i < FA.ICE_DOMES.length; i++) {
      var d = FA.ICE_DOMES[i];
      var sc = FA.curve(d.s, bp);
      if (sc <= 0.001) continue;
      var lat = d.c[0], lon = d.c[1];
      if (d.move) {
        lat = FA.curve(d.move.map(function (m) { return [m[0], m[1]]; }), bp);
        lon = FA.curve(d.move.map(function (m) { return [m[0], m[2]]; }), bp);
      }
      var c = vec(lat, lon);
      var east = [-Math.sin(lon * D2R), Math.cos(lon * D2R), 0];
      var north = cross(c, east);
      var az = d.az * D2R;
      var t = [north[0] * Math.cos(az) + east[0] * Math.sin(az), north[1] * Math.cos(az) + east[1] * Math.sin(az), north[2] * Math.cos(az) + east[2] * Math.sin(az)];
      var s = cross(c, t);
      var a = Math.sin(d.a * sc * D2R), b = Math.sin(d.b * sc * D2R);
      C.set([c[0], c[1], c[2], 1], n * 4);
      T.set([t[0], t[1], t[2], a], n * 4);
      S.set([s[0], s[1], s[2], b], n * 4);
      n++;
      if (n >= FA.MAX_DOMES) break;
    }
    for (i = n; i < FA.MAX_DOMES; i++) { C[i * 4 + 3] = 0; T[i * 4 + 3] = 1; S[i * 4 + 3] = 1; }
    out.count = n;
    return out;
  };
